  var lang = 'ru';
  var listeners = [];

  function initial() {
    var q = null, saved = null;
    try { q = new URLSearchParams(location.search).get('lang'); } catch (e) {}
    try { saved = localStorage.getItem('nami-lang'); } catch (e) {}
    var fromHtml = document.documentElement.getAttribute('lang');
    return [q, saved, fromHtml].filter(function (l) { return LANGS.indexOf(l) > -1; })[0] || 'ru';
  }

  function t(key, vars) {
    var s = (dict[lang] && dict[lang][key]);
    if (s == null) s = dict.ru[key];
    if (s == null) s = key;
    if (vars) s = s.replace(/\{(\w+)\}/g, function (_, k) { return vars[k] != null ? vars[k] : ''; });
    return s;
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
    root.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var p = pair.split(':');
        if (p.length === 2) el.setAttribute(p[0].trim(), t(p[1].trim()));
      });
    });
    var html = document.documentElement;
    html.lang = lang;
    document.title = t('meta.title');
    var md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', t('meta.desc'));
    document.querySelectorAll('[data-lang]').forEach(function (b) {
      if (b.hasAttribute('aria-pressed')) b.setAttribute('aria-pressed', String(b.getAttribute('data-lang') === lang));
    });
  }

  function set(l) {
    if (LANGS.indexOf(l) < 0) return;
    lang = l;
    try { localStorage.setItem('nami-lang', l); } catch (e) {}
    apply();
    listeners.forEach(function (fn) { fn(l); });
  }

  function num(n) { return new Intl.NumberFormat(LOCALES[lang]).format(n); }
  function money(n) { return num(n) + ' ₼'; }

  return {
    LANGS: LANGS,
    NAMES: NAMES,
    t: t,
    apply: apply,
    set: set,
    init: function () { lang = initial(); apply(); },
    get: function () { return lang; },
    onChange: function (fn) { listeners.push(fn); },
    num: num,
    money: money
  };
